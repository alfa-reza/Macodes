package dev.termish.mosh

import dev.termish.term.CellAttr
import dev.termish.term.TerminalBuffer
import dev.termish.term.TerminalEmulator
import kotlinx.coroutines.runBlocking
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock

/**
 * SSP Remote State (the client-side shadow corresponding to the server-side terminal state):
 * A complete terminal (parser + screen buffer), evolving according to the HostMessage diff.
 *
 * Reuse the project's in-house pure Kotlin terminal emulator. mosh's Complete does not replicate the parser state
 * (Note: "parser state" is irrelevant); when branching, use a deep copy of the same buffer + a new parser to parse:
 * The diff generated by `new_frame` consists of a complete escape sequence and does not break the sequence in the middle.
 */
internal class ShadowTerminal internal constructor(
    val buffer: TerminalBuffer,
    private val emulator: TerminalEmulator,
    var echoAck: ULong,
) {
    /**
     * Buffer read/write locks: session coroutines (applyDiff / resize / fork) and UI copy threads
     * (copyContentFrom) Concurrently access the same TerminalBuffer; if not locked, resizing may be interrupted midway
     * The row's cells and the cols field get out of sync; `cloneLine` will crash out of bounds (`ArrayIndexOutOfBounds`).
     */
    internal val lock = Mutex()

    var onTitleChange: (String) -> Unit = {}
        set(v) {
            field = v
            emulator.onTitleChange = v
        }
    var onClipboardWrite: (String) -> Unit = {}
        set(v) {
            field = v
            emulator.onClipboardWrite = v
        }

    /** Apply HostMessage diff (hostbytes → terminal; resize → resize; echoack → record).
     *
     *  Note: the resize/alt screen semantics of this shadow (xterm-style bottom anchoring, scrollback preserved, 1049 restore
     *  screen) intentionally does [not] mirror the mosh server—the mosh Framebuffer has no scrollback and no alt screen
     *  (1049 is ignored; leaving a ghost image when exiting Vim is a well-known bug), resizing with top anchoring causes bottom rows to be lost.
     *  Server-side models are more limited; byte-for-byte mirroring actually degrades the user experience; diffs only apply to the visible area by row numbers,
     *  Semantic differences do not violate the protocol. Do not change this to “alignment with the server.” */
    fun applyDiff(diff: ByteArray) {
        runBlocking {
            lock.withLock {
                for (ev in decodeHostMessage(diff)) {
                    when (ev) {
                        is HostEventIn.HostBytes -> emulator.write(ev.bytes)
                        is HostEventIn.Resize -> buffer.resize(ev.width, ev.height)
                        is HostEventIn.EchoAck -> if (ev.echoAckNum > echoAck) echoAck = ev.echoAckNum
                    }
                }
            }
        }
    }

    /** Fork: Deep copy the current state (mosh receiver-side timestamp state copy). */
    fun fork(): ShadowTerminal =
        runBlocking {
            lock.withLock {
                // COW Shallow Forking: Row object sharing and copy-on-write, reducing the cost of each state update from O(cell) to O(number of rows)
                val buf = buffer.shallowFork()
                val emu = TerminalEmulator(buf)
                emu.onTitleChange = onTitleChange
                emu.onClipboardWrite = onClipboardWrite
                // The shadow terminal should not send responses to external systems (such as DSR responses); simply leave this field blank.
                ShadowTerminal(buf, emu, echoAck)
            }
        }

    /** Local prediction echo: Replay the effects of the user input whitelist on a COW fork in a confirmed state (mosh
     *  (A simplified version of byte-by-byte prediction). Supports:
     *  - Printable characters (including UTF-8 multibyte sequences): Feed directly to the forked emulator
     *  - 0x7f Backspace: The prediction behavior when `readline` echoes "\b \b" (the cursor moves back and deletes characters)
     *  - CR: shell canonical mode echoes \r\n (mosh newline_carriage_return)
     *  - Left/Right arrow keys (CSI/SS3 C, D): Move the cursor
     *  Remaining control bytes → Return null (skip prediction for this segment; mosh’s conservative alignment strategy).
     *  Used to show information; does not enter the SSP state machine; is discarded immediately after confirming an echo_ack acknowledgment. */
    internal fun predictInput(
        bytes: ByteArray,
        underline: Boolean,
    ): ShadowTerminal? {
        val fork = fork()
        val buf = fork.buffer
        if (underline) buf.currentAttrs = buf.currentAttrs or CellAttr.UNDERLINE
        var i = 0
        var textStart = 0

        fun flushText(until: Int) {
            if (until > textStart) fork.emulator.write(bytes.copyOfRange(textStart, until))
        }
        while (i < bytes.size) {
            val b = bytes[i].toInt() and 0xff
            when {
                b == 0x7f -> {
                    flushText(i)
                    i++
                    // You can only backspace if the cursor is not at the beginning of the row (mosh: cursor().col > 0); when using `pendingWrap`,
                    // The backspace first undoes the deferred line wrap, which is exactly equivalent to erasing the character that just wrapped at the end of the line.
                    if (buf.cursorCol > 0 || buf.pendingWrap) {
                        buf.backspace()
                        buf.putChar(' '.code)
                        buf.backspace()
                    }
                    textStart = i
                }
                b == 0x0d -> {
                    flushText(i)
                    i++
                    fork.emulator.write(CR_LF)
                    textStart = i
                }
                b == 0x1b -> {
                    flushText(i)
                    val ok =
                        i + 2 < bytes.size &&
                            (bytes[i + 1] == '['.code.toByte() || bytes[i + 1] == 'O'.code.toByte()) &&
                            (bytes[i + 2] == 'C'.code.toByte() || bytes[i + 2] == 'D'.code.toByte())
                    if (!ok) return null
                    fork.emulator.write(bytes.copyOfRange(i, i + 3))
                    i += 3
                    textStart = i
                }
                b < 0x20 -> return null // Do not perform any prediction on the remaining control bytes.
                else -> i++ // Printable/UTF-8 bytes: Write in batches
            }
        }
        flushText(bytes.size)
        return fork
    }

    companion object {
        private val CR_LF = byteArrayOf(0x0d, 0x0a)

        fun create(
            cols: Int,
            rows: Int,
        ): ShadowTerminal {
            // The shadow must be a complete mirror of the server's framebuffer (the mosh Framebuffer has no scroll limit);
            // The scrollback limit of the UI rendering layer is clipped by `uiBuffer` itself; the shadow must not truncate, or the diff will misalign
            val buf = TerminalBuffer(cols, rows, maxScrollbackLines = Int.MAX_VALUE)
            val emu = TerminalEmulator(buf)
            return ShadowTerminal(buf, emu, 0u)
        }
    }
}
