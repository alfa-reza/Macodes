/** 根据设置解析语言：空 = 跟随系统（系统语言为中文时用中文，其余英文）。 */
fun appStringsFor(language: String): AppStrings =
    when (language) {
        "zh" -> ZhStrings
        "en" -> EnStrings
        else ->
            if (Locale.current.language
                    .lowercase()
                    .startsWith("zh")
            ) {
                ZhStrings
            } else {
                EnStrings
            }
    }

private val EnShortMonths =
    listOf("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")

internal fun formatEnglishMonthDay(
    day: Int,
    monthNumber: Int,
    year: Int? = null,
): String {
    val month = EnShortMonths.getOrElse(monthNumber - 1) { monthNumber.toString() }
    return if (year == null) "$day $month" else "$day $month $year"
}

